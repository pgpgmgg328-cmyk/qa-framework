    key = "ozon"
    title = "Ozon Profit (task.ozon.ru)"
    settings = {
        "TARGET_URL": "https://task.ozon.ru",
        # задание — в главном фрейме; агент работает в нём только на страницах заданий
        "FRAME_KEYWORDS": (),
        "ALLOW_MAIN_FRAME": True,
        "TASK_URL_KEYWORDS": ("/task/",),
        "NON_TASK_URL_KEYWORDS": ("/instruction",),
        "ORDERS_BUTTON_TEXTS": ("приступить",),
        "ORDERS_DONE_TEXTS": ("закончились задачи",),
        "FINISH_BUTTON_TEXTS": ("отправить",),
        # тренировка не пропускает неверный ответ: задание не меняется, всплывает «Ошибка — Для отправки
        # ответа необходимо решить все задания» (тот же текст и при неполном ответе — его агент не шлёт)
        "WRONG_ANSWER_TEXTS": ("необходимо решить все задания",),
        # «Пропустить 0/10» — пропуски ограничены (10 в день): агент задание не пропускает, а решает
        # или зовёт человека. Добавляется к общему стоп-списку FINISH_DENY_SUBSTRINGS
        "EXTRA_DENY_SUBSTRINGS": ("пропустить",),
        # вид задания — проект (/task/<id>): варианты ответа здесь — названия товаров, а не категории,
        # и по структуре формы каждая страница выглядела бы новым видом
        "POOL_URL_RE": r"/task/[^/?#]+",
        # классы Ozon UI с хэшем на конце (ozi__window__window__lcYqb) — поэтому «*=»
        "DIALOG_SELECTORS": ('[class*="ozi__window__window"]',),
        "PAGE_SKIP_SELECTORS": (
            '[class*="ozi__header__header"]',
            '[data-testid="PageHeaderBackLink"]',
            '[data-testid="ChatUrlButton"]',
        ),
    }
