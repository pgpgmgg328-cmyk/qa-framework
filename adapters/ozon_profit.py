"""Ozon Profit — задания на task.ozon.ru (кабинет profit.ozon.ru открывает их в новой вкладке).

Изучено на живом сайте (октябрь 2026, тренировки «Определение одинаковых товаров», «Выбор
одинаковых названий товаров», «Проверьте корректность цен на товар по фото»):

- Список проектов — https://task.ozon.ru/ (Nuxt). На карточке метка «Тренировка» / «Платное» /
  «Экзамен», кнопки «Инструкция» и «Приступить» (ссылка /task/<id>). Проект выбирает человек.
- Задание открывается в ГЛАВНОМ фрейме (iframe нет): /task/<id>. На одной странице несколько
  блоков (2–10), у каждого своя группа обычных <input type="radio"> внутри <label>, и одна кнопка
  «Отправить» на все блоки. После «Отправить» адрес не меняется — на месте блоков появляются
  новые; в тренировке «верно / неверно» страница не показывает.
- Инструкция — боковое окно (drawer) без role="dialog": div.ozi__window__window…, у кнопки
  закрытия нет ни текста, ни aria-label (закрывается и клавишей Escape). При первом заходе в
  проект окно открывается само, через несколько секунд после загрузки страницы.
- Задачи проекта кончились — на той же странице «Вы молодец! … В текущем проекте закончились
  задачи! Возвращайтесь к списку проектов» и ссылка «К списку проектов».
- Над заданием — шапка сайта (Задания, Статистика, Обучение, Уведомления, Ozon ID …), ссылки
  «Все задания» и «Чат с заказчиком»: модели они не показываются.
"""

